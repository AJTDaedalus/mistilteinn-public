"""Potential row tagging, verified against a real seeded DB (#90, Task 6).

The oracle is `app/data/validation/potential_deltas.json`, generated by
`scripts/snapshot_potential_deltas.py` and **stamped with the nanoka version it came
from**. Counts are deliberately not literals in this file: the roster moves every patch,
and a literal that goes stale gets "fixed" by overwriting it. Revision 1 of the DESIGN
hardcoded 192/218 from nanoka 3.2.1 and was both stale *and* wrong by the time the work
started -- it claimed Koleda 19 -> 21, but Koleda's damage params sit on a shared
description entry, so only its text differs between the states and its row counts are
identical. Regenerating is a reviewable step; re-baselining a literal is not.

Set POTENTIAL_REQUIRE_DB=1 to turn every "seeded DB required" skip into a failure, the
same contract as CROSSVAL_REQUIRE_DB. A skip here is *cannot check*, never *clean*: an
upgraded-but-not-re-seeded DB has `potential` NULL on every row, which reads as "every
row is shared" and makes the whole toggle silently inert.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest
from sqlalchemy import func, select

from app.database import async_session_factory
from app.models.agent import Agent, AgentSkill, Attack, CoreSkill
from app.models.enums import PotentialVariant

_SNAPSHOT_PATH = (
    Path(__file__).parent.parent.parent / "app" / "data" / "validation" / "potential_deltas.json"
)
_REQUIRE_DB = bool(os.environ.get("POTENTIAL_REQUIRE_DB"))

_REGENERATE = (
    "If nanoka has bumped past the snapshot's version, regenerate with "
    "`python -m scripts.snapshot_potential_deltas` and REVIEW THE DIFF -- do not "
    "regenerate to make this green without reading what moved."
)

_MODELS = {"attacks": Attack, "agent_skills": AgentSkill, "core_skills": CoreSkill}


def _snapshot() -> dict:
    return json.loads(_SNAPSHOT_PATH.read_text())


def _skip_or_fail(reason: str) -> None:
    """Skip normally; fail loudly under POTENTIAL_REQUIRE_DB."""
    if _REQUIRE_DB:
        pytest.fail(f"POTENTIAL_REQUIRE_DB is set but the data is missing: {reason}")
    pytest.skip(reason)


@pytest.fixture
async def seeded() -> bool:
    """True when the app DB is reachable, seeded, AND carries Potential tags."""
    try:
        async with async_session_factory() as session:
            agents = (
                await session.execute(select(func.count()).select_from(Agent))
            ).scalar_one()
            if not agents:
                return False
            # The tag is importer-assigned, so a migrated-but-not-re-seeded DB has it
            # NULL everywhere. That is the `ex_energy_cost` failure shape: present,
            # queryable, and meaning something other than what the reader assumes.
            tagged = (
                await session.execute(
                    select(func.count()).select_from(Attack).where(Attack.potential.is_not(None))
                )
            ).scalar_one()
    except Exception:
        return False
    return bool(tagged)


async def _counts(session, model, agent_id: str) -> dict[str, int]:
    rows = (
        await session.execute(
            select(model.potential, func.count())
            .where(model.agent_id == agent_id)
            .group_by(model.potential)
        )
    ).all()
    out = {"shared": 0, "base": 0, "unlocked": 0}
    for tag, count in rows:
        out[tag or "shared"] = count
    return out


class TestSnapshotAgreement:
    async def test_per_agent_counts_match_the_snapshot(self, seeded: bool) -> None:
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")
        snap = _snapshot()

        mismatches: list[str] = []
        async with async_session_factory() as session:
            for agent_name, tables in snap["agents"].items():
                agent_id = (
                    await session.execute(select(Agent.id).where(Agent.name == agent_name))
                ).scalar_one_or_none()
                if agent_id is None:
                    mismatches.append(f"{agent_name}: in snapshot but not in the DB")
                    continue
                for table_name, expected in tables.items():
                    actual = await _counts(session, _MODELS[table_name], agent_id)
                    if actual != expected:
                        mismatches.append(
                            f"{agent_name}/{table_name}: expected {expected}, got {actual}"
                        )

        assert not mismatches, (
            f"Potential row counts moved (snapshot nanoka version "
            f"{snap['nanoka_version']}):\n  " + "\n  ".join(mismatches) + f"\n\n{_REGENERATE}"
        )

    async def test_roster_size_matches(self, seeded: bool) -> None:
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")
        snap = _snapshot()
        async with async_session_factory() as session:
            agents = (
                await session.execute(select(func.count()).select_from(Agent))
            ).scalar_one()
        assert agents == snap["agent_count"], (
            f"Roster is {agents}, snapshot says {snap['agent_count']}. {_REGENERATE}"
        )


class TestInvariants:
    """Properties that hold regardless of which patch the DB was seeded from."""

    async def test_no_agent_outside_the_snapshot_carries_a_tag(self, seeded: bool) -> None:
        """The ~49 agents with no Potential must have every row untagged.

        This is the assertion that replaces listing them as rows of zeroes, and it is
        the one that catches a classifier that has started tagging indiscriminately.
        """
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")
        expected_names = set(_snapshot()["agents"])

        async with async_session_factory() as session:
            rows = (
                await session.execute(
                    select(Agent.name, func.count())
                    .join(Attack, Attack.agent_id == Agent.id)
                    .where(Attack.potential.is_not(None))
                    .group_by(Agent.name)
                )
            ).all()
            skill_rows = (
                await session.execute(
                    select(Agent.name, func.count())
                    .join(AgentSkill, AgentSkill.agent_id == Agent.id)
                    .where(AgentSkill.potential.is_not(None))
                    .group_by(Agent.name)
                )
            ).all()

        tagged = {name for name, _ in rows} | {name for name, _ in skill_rows}
        assert tagged <= expected_names, (
            f"Agents carry Potential tags but are not in the snapshot: "
            f"{sorted(tagged - expected_names)}. {_REGENERATE}"
        )

    async def test_unlocked_never_sees_fewer_rows_than_locked(self, seeded: bool) -> None:
        """Potential adds content; it never removes a move.

        RESEARCH_potential_sweep_85.md §5: zero move names are base-only-with-no-
        Potential-twin roster-wide. A locked kit with *more* rows than the unlocked one
        would mean the classifier has inverted.
        """
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        # Against the DB, not the snapshot: asserting this over the fixture would only
        # prove the fixture is self-consistent.
        async with async_session_factory() as session:
            for agent_name in _snapshot()["agents"]:
                agent_id = (
                    await session.execute(select(Agent.id).where(Agent.name == agent_name))
                ).scalar_one()
                for table_name, model in _MODELS.items():
                    counts = await _counts(session, model, agent_id)
                    locked = counts["shared"] + counts["base"]
                    unlocked = counts["shared"] + counts["unlocked"]
                    assert unlocked >= locked, (
                        f"{agent_name}/{table_name}: locked kit has {locked} rows but "
                        f"unlocked only {unlocked} — the classifier looks inverted"
                    )

    async def test_each_variant_is_contiguous_from_zero(self, seeded: bool) -> None:
        """The `hit_index` invariant, against real data rather than a fixture.

        For every (agent, move), the rows a locked build sees must be numbered
        0..n-1 with no gaps, and so must the rows an unlocked build sees. A merged
        numbering pass leaves the locked kit reading [0,1,2,4,5,6] — the #85 artefact.

        Variant-labelled moves are excluded: their rows are mutually-exclusive game
        states rather than a press chain, so they legitimately repeat an index.
        """
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        async with async_session_factory() as session:
            rows = (
                await session.execute(
                    select(
                        Agent.name,
                        Attack.name,
                        Attack.hit_index,
                        Attack.potential,
                        Attack.hit_mode,
                    )
                    .join(Attack, Attack.agent_id == Agent.id)
                    .where(Agent.name.in_(list(_snapshot()["agents"])))
                    .where(Attack.variant_label.is_(None))
                )
            ).all()

        moves: dict[tuple[str, str], list] = {}
        for agent_name, move_name, hit_index, tag, hit_mode in rows:
            if str(hit_mode) == "variant":
                continue
            moves.setdefault((agent_name, move_name), []).append((hit_index, tag))

        broken: list[str] = []
        for (agent_name, move_name), hits in moves.items():
            for variant, allowed in (("locked", "base"), ("unlocked", "unlocked")):
                indices = sorted(i for i, tag in hits if tag is None or tag == allowed)
                if indices and indices != list(range(len(indices))):
                    broken.append(f"{agent_name} / {move_name} [{variant}]: {indices}")

        assert not broken, (
            "Non-contiguous hit_index — each Potential state must be numbered on its "
            "own pass (DESIGN_potential_toggle.md §4.2):\n  " + "\n  ".join(broken)
        )


class TestMoveSpecHits:
    """Task 8/9 — authored `hits` must agree with the per-variant DB row count.

    `MoveBuildupSpec.hits` is load-bearing three ways: the fallback hit count, the
    sequential buildup divisor, and (since #83) the sequential *clock* divisor. Those
    last two read `move_spec.hits` **directly** rather than the row count, so they do
    not benefit from the repository's variant filter — an authored value taken from the
    unlocked kit would mis-divide both gauge and time for a locked build, with no test
    failing. That is the `ex_energy_cost` shape: a value that is present but means
    something else.

    As of #90 the conflict set is **empty**, and empirically rather than by assumption:
    of the 17 moves whose row count differs between the states, 16 simply do not exist
    in the locked kit (so the variant-filtered `len(step.attacks)` derives the right
    count for free), and the seventeenth -- Soldier 11's `Basic Attack: Fire
    Suppression`, 4 rows locked vs 7 unlocked -- has no authored spec at all, because
    no `soldier_11.json` exists. No `potential_locked` override data was needed.

    Revision 1 of the DESIGN proposed hand-authoring overrides for "Soldier 11 Fire
    Suppression 4 vs 7" and "Koleda Smash 'n' Bash 6 vs 8". The first names a file that
    does not exist; the second names an agent whose row counts are identical in both
    states. Hand-authored duplicates of a DB fact are how the two drift -- so this is a
    guard rather than a data set, and it is what turns the silent failure loud on the
    day a curator authors a spec for one of these agents.
    """

    async def test_no_authored_hits_conflicts_with_a_variant_row_count(
        self, seeded: bool
    ) -> None:
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        from app.data.loaders.moves import load_agent_moves

        potential_agents = set(_snapshot()["agents"])
        specs_by_agent = {
            agent["agent_name"]: agent["moves"]
            for agent in load_agent_moves().values()
            if isinstance(agent, dict) and "agent_name" in agent
        }

        async with async_session_factory() as session:
            rows = (
                await session.execute(
                    select(Agent.name, Attack.name, Attack.potential)
                    .join(Attack, Attack.agent_id == Agent.id)
                    .where(Agent.name.in_(list(potential_agents)))
                )
            ).all()

        per_move: dict[tuple[str, str], dict[str, int]] = {}
        for agent_name, move_name, tag in rows:
            counts = per_move.setdefault((agent_name, move_name), {"locked": 0, "unlocked": 0})
            for variant, allowed in (("locked", "base"), ("unlocked", "unlocked")):
                if tag is None or tag == allowed:
                    counts[variant] += 1

        conflicts: list[str] = []
        for agent_name, moves in specs_by_agent.items():
            if agent_name not in potential_agents:
                continue
            for move_name, spec in moves.items():
                counts = per_move.get((agent_name, move_name))
                if counts is None or counts["locked"] == counts["unlocked"]:
                    continue
                conflicts.append(
                    f"{agent_name} / {move_name}: authored hits={spec.hits} but the "
                    f"kits differ ({counts['locked']} locked vs {counts['unlocked']} "
                    f"unlocked) — needs a per-variant override"
                )

        assert not conflicts, (
            "A move spec authors `hits` for a move whose hit count depends on Potential "
            "state. `hits` drives the sequential buildup AND clock divisors directly, so "
            "one value cannot serve both kits:\n  " + "\n  ".join(conflicts)
        )


class TestEndToEnd:
    """DESIGN §6 test 4 — the toggle changes what the calc sees, and only where it should."""

    async def test_rank_changes_the_resolved_row_set_for_an_affected_agent(
        self, seeded: bool
    ) -> None:
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        from app.repositories.attack import AttackRepository

        async with async_session_factory() as session:
            repo = AttackRepository(session)
            agent_id = str(
                (await session.execute(select(Agent.id).where(Agent.name == "Ellen"))).scalar_one()
            )
            locked = await repo.get_by_agent(agent_id, PotentialVariant.for_rank(0))
            unlocked = await repo.get_by_agent(agent_id, PotentialVariant.for_rank(5))

        assert len(unlocked) > len(locked), "Ellen's Potential kit must add rows"
        # And the added rows are moves the locked kit genuinely lacks, not duplicates.
        locked_names = {a.name for a in locked}
        unlocked_names = {a.name for a in unlocked}
        assert unlocked_names > locked_names
        assert "Basic Attack: Icy Blade" in unlocked_names - locked_names

    async def test_rank_is_inert_for_an_unaffected_agent(self, seeded: bool) -> None:
        """One of the ~49 agents without Potential must be byte-identical across ranks."""
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        from app.repositories.attack import AttackRepository

        async with async_session_factory() as session:
            repo = AttackRepository(session)
            name = next(
                n
                for (n,) in (await session.execute(select(Agent.name))).all()
                if n not in _snapshot()["agents"] and not n.startswith("Avatar_")
            )
            agent_id = str(
                (await session.execute(select(Agent.id).where(Agent.name == name))).scalar_one()
            )
            locked = await repo.get_by_agent(agent_id, PotentialVariant.for_rank(0))
            unlocked = await repo.get_by_agent(agent_id, PotentialVariant.for_rank(5))

        def fingerprint(rows: list) -> list[tuple]:
            return sorted(
                (r.name, r.hit_index, r.damage_base, r.damage_growth, r.anomaly_buildup)
                for r in rows
            )

        assert fingerprint(locked) == fingerprint(unlocked), (
            f"{name} has no Potential data, so the toggle must not change a single row"
        )
        assert locked, f"{name} returned no rows at all — the filter is over-matching"

    async def test_every_locked_row_set_is_a_real_subset_or_equal(self, seeded: bool) -> None:
        """No agent may return rows of BOTH variants on a calc path.

        The leakage failure mode: a query with no variant predicate returns base AND
        unlocked rows, which double-counts every hit the two kits disagree about.
        """
        if not seeded:
            _skip_or_fail("app DB unreachable, unseeded, or seeded before #90's tagging")

        from app.repositories.attack import AttackRepository

        async with async_session_factory() as session:
            repo = AttackRepository(session)
            for agent_name in _snapshot()["agents"]:
                agent_id = str(
                    (
                        await session.execute(select(Agent.id).where(Agent.name == agent_name))
                    ).scalar_one()
                )
                for variant in (PotentialVariant.LOCKED, PotentialVariant.UNLOCKED):
                    rows = await repo.get_by_agent(agent_id, variant)
                    tags = {r.potential for r in rows if r.potential}
                    forbidden = "unlocked" if variant is PotentialVariant.LOCKED else "base"
                    assert forbidden not in tags, (
                        f"{agent_name} at {variant}: leaked {forbidden!r}-tagged rows"
                    )
