"""Write GO's non-stacking weapon buffs as a committed snapshot.

    cd backend && python -m scripts.build_go_nonstack --src /path/to/genshin-optimizer

Math-fallback P3, owner approval 2026-11-14 (`docs/DECISIONS.md` §45): *"Millennial Movement:
one"*. GO marks a team buff that does not stack with another of its kind by wrapping it in
`nonStackBuff(name, path, node)` (`libs/gi/sheets/src/SheetUtil.tsx:102-117`): the buff applies
only for the member `input.nonStacking[name]` names, and every wielder whose condition holds
writes its own character key there. Two weapons that share a `name` are one family — the
Millennial Movement series is the names GO spells `millenial*` (Freedom-Sworn, Song of Broken
Pines, Elegy for the End) — and a weapon whose name no other weapon uses is a family of one
(two wielders of the same weapon).

**Which weapons share a family is read from GO's sheets, never written from memory.** This
script parses every `libs/gi/sheets/src/Weapons/<Type>/<Key>/index.tsx` at `GO_COMMIT` for the
first argument of each `nonStackBuff(` call and records it with its file and line. A name GO
writes as a template (`hakushin${key}`) is recorded as written; `weapon_passives` expands it.

`--src` may be a clone or any directory holding the sheets at their repository paths; the
commit is checked when the directory is a git clone.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "backend" / "app" / "data" / "formula" / "weapon_nonstack_go.json"

#: The GO commit every weapon passive file cites (`app/data/formula/weapons/*.json`).
GO_COMMIT = "2c13fc40c4694fd8beae513493c4c8a7537173c6"
WEAPONS = Path("libs/gi/sheets/src/Weapons")

_CALL = re.compile(r"nonStackBuff\(\s*(['`])([^'`]+)\1")
#: Where GO resolves the name to one writer: the `small` string accumulator.
RULE = "libs/gi/uidata/src/uiData.ts:217-218,266-276"


def _line(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def families(root: Path) -> dict[str, dict[str, list[str]]]:
    """`{weapon key: {name: [file:line, …]}}` for every sheet that calls `nonStackBuff`."""
    out: dict[str, dict[str, list[str]]] = {}
    for sheet in sorted((root / WEAPONS).glob("*/*/index.tsx")):
        text = sheet.read_text()
        found: dict[str, list[str]] = {}
        for match in _CALL.finditer(text):
            where = f"{sheet.relative_to(root)}:{_line(text, match.start())}"
            found.setdefault(match.group(2), []).append(where)
        if found:
            out[sheet.parent.name] = dict(sorted(found.items()))
    return out


def main() -> None:
    """Write the snapshot from GO's sheets at `GO_COMMIT`."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, required=True, help="GO's sheets at GO_COMMIT")
    args = parser.parse_args()
    if (args.src / ".git").exists():
        head = subprocess.run(  # noqa: S603 - fixed argv, path from the operator
            ["git", "-C", str(args.src), "rev-parse", "HEAD"],  # noqa: S607
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        if head != GO_COMMIT:
            msg = f"the clone is at {head}; the weapon files cite GO {GO_COMMIT}."
            raise SystemExit(msg)
    weapons = families(args.src)
    snapshot = {
        "go_commit": GO_COMMIT,
        "source": f"github.com/frzyc/genshin-optimizer — {WEAPONS}/<Type>/<Key>/index.tsx (MIT)",
        "rule": RULE,
        "note": (
            "Each weapon sheet's nonStackBuff names, keyed by GO's sheet directory, with the "
            "file:line of each call. Weapons sharing a name share one buff: GO applies it for "
            "the one member input.nonStacking[name] resolves to, the writer whose character key "
            "sorts first (`rule`). Generated by scripts/build_go_nonstack.py; do not edit by "
            "hand."
        ),
        "weapons": weapons,
    }
    OUT.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {OUT.relative_to(REPO)} at GO {GO_COMMIT[:12]}: {len(weapons)} weapons")


if __name__ == "__main__":
    main()
