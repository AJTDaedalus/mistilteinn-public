"""Regenerate the Potential row-count snapshot from a seeded DB (#90).

The snapshot is the oracle for `tests/integration/test_potential_seed_deltas.py`. It
records, per agent, how many `attacks` / `agent_skills` / `core_skills` rows each
Potential state sees -- together with **the nanoka version it was derived from**.

Why a generated snapshot rather than counts written into a test: the roster moves every
patch. Revision 1 of `docs/DESIGN_potential_toggle.md` hardcoded "192 locked / 218
unlocked" measured at nanoka 3.2.1, and by the time the work started that was both stale
*and wrong* -- its Koleda row claimed 19 -> 21, but Koleda's damage params live on a
shared description entry, so its numbers are identical in both states and only its text
differs. A literal in a test would have been "fixed" by overwriting it.

So: a patch bump makes the test fail with an instruction to run this script and **review
the diff**, which is a deliberate reviewable step. Never regenerate to make a red test
green without reading what moved.

Usage:
    cd backend && python -m scripts.snapshot_potential_deltas            # resolve version
    cd backend && python -m scripts.snapshot_potential_deltas --version 3.2.2+18097913
"""

from __future__ import annotations

import argparse
import asyncio
import json
from pathlib import Path

import httpx
from sqlalchemy import func, select

from app.data.importers.nanoka_importer import BASE_URL
from app.database import async_session_factory
from app.models.agent import Agent, AgentSkill, Attack, CoreSkill

SNAPSHOT_PATH = Path(__file__).parent.parent / "app" / "data" / "validation" / "potential_deltas.json"

_TABLES = (("attacks", Attack), ("agent_skills", AgentSkill), ("core_skills", CoreSkill))


async def _resolve_version() -> str:
    """The nanoka version a seed run would pick -- `manifest.zzz.latest`."""
    async with httpx.AsyncClient(timeout=30.0) as client:
        resp = await client.get(f"{BASE_URL}/manifest.json")
        resp.raise_for_status()
        return resp.json()["zzz"]["latest"]


async def collect() -> dict[str, dict[str, dict[str, int]]]:
    """Per-agent, per-table counts bucketed by Potential tag."""
    out: dict[str, dict[str, dict[str, int]]] = {}
    async with async_session_factory() as session:
        for table_name, model in _TABLES:
            rows = (
                await session.execute(
                    select(Agent.name, model.potential, func.count())
                    .join(model, model.agent_id == Agent.id)
                    .group_by(Agent.name, model.potential)
                )
            ).all()
            for agent_name, tag, count in rows:
                bucket = out.setdefault(agent_name, {}).setdefault(
                    table_name, {"shared": 0, "base": 0, "unlocked": 0}
                )
                bucket[tag or "shared"] = count
    return out


def _has_variants(per_table: dict[str, dict[str, int]]) -> bool:
    return any(t["base"] or t["unlocked"] for t in per_table.values())


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", help="nanoka version the DB was seeded from")
    args = parser.parse_args()

    version = args.version or await _resolve_version()
    counts = await collect()
    if not counts:
        raise SystemExit("No agents in the DB -- seed it first (python -m scripts.seed_db)")

    # Only agents that carry a tagged row anywhere are recorded. Listing the other ~49
    # would be 49 rows of zeroes that churn on every roster addition; the test asserts
    # their emptiness as an invariant instead.
    affected = {name: tables for name, tables in sorted(counts.items()) if _has_variants(tables)}

    snapshot = {
        "_comment": (
            "Generated by scripts/snapshot_potential_deltas.py -- do not hand-edit. "
            "Counts are per Potential tag: a LOCKED build sees shared+base, an UNLOCKED "
            "build sees shared+unlocked. Regenerate only when nanoka bumps, and review "
            "the diff (docs/DESIGN_potential_toggle.md, issue #90)."
        ),
        "nanoka_version": version,
        "agent_count": len(counts),
        "agents_with_potential": len(affected),
        "agents": affected,
    }

    SNAPSHOT_PATH.write_text(json.dumps(snapshot, indent=2, sort_keys=False) + "\n")
    print(f"Wrote {SNAPSHOT_PATH.relative_to(Path.cwd())}")
    print(f"  nanoka version : {version}")
    print(f"  agents         : {len(counts)} ({len(affected)} with Potential variants)")
    for name, tables in affected.items():
        atk = tables.get("attacks", {"shared": 0, "base": 0, "unlocked": 0})
        print(
            f"    {name:20} attacks locked={atk['shared'] + atk['base']:3} "
            f"unlocked={atk['shared'] + atk['unlocked']:3}"
        )


if __name__ == "__main__":
    asyncio.run(main())
