"""Snapshot every gcsim source line the formula energy model cites, at the pin.

    cd backend && python -m scripts.gcsim.snapshot_particle_lines --src /path/to/gcsim

The particle table (`app/data/formula/energy/particles.json`) cites each count to a
`QueueParticle` call (and each flat refund to its `AddEnergy`, the Favonius proc to its
weapon file, a character left to the user to the lines that say why), and the energy model's
constants cite gcsim's `ReceiveParticle`, its energy drip and its own ER-requirement
formula. This copies each cited line, verbatim, into
`app/data/formula/energy/gcsim_lines.json`, so `tests/unit/test_formula_energy_data.py` can
hold every number to the line it names without gcsim's source or the network (the rule
`app/data/gcsim/keys.json` follows). A snapshot built from another commit is refused.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from scripts.gcsim.build_key_snapshot import declared_pin

REPO = Path(__file__).resolve().parents[3]
DATA = REPO / "backend" / "app" / "data" / "formula" / "energy"
TABLE = DATA / "particles.json"
OUT = DATA / "gcsim_lines.json"

#: The model's constants, each a range of lines (inclusive) in gcsim at the pin.
CONSTANT_LINES: dict[str, tuple[str, int, int]] = {
    "off_field": ("pkg/core/player/character/energy.go", 56, 60),
    "particle_value": ("pkg/core/player/character/energy.go", 61, 71),
    "er_multiplies": ("pkg/core/player/character/energy.go", 72, 77),
    "flat_energy": ("pkg/core/player/character/energy.go", 35, 43),
    "distribute": ("pkg/core/player/player.go", 197, 200),
    "drip": ("pkg/simulation/setup.go", 522, 531),
    "requirement": ("pkg/optimization/optstats/energy_stats.go", 83, 86),
}


def _cited(table: dict) -> set[tuple[str, int]]:
    lines: set[tuple[str, int]] = set()
    entries = [s for c in table["characters"].values()
               for s in (*c["sources"], *c.get("refunds", ()))]
    entries += list(table.get("weapons", {}).values())
    entries += list(table.get("not_curated", {}).values())
    for entry in entries:
        for path, line, _needle in entry["lines"]:
            lines.add((path, int(line)))
    for path, start, end in CONSTANT_LINES.values():
        lines.update((path, n) for n in range(start, end + 1))
    return lines


def main() -> None:
    """Write the snapshot from a gcsim checkout at the pin."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--src", type=Path, required=True, help="a gcsim clone at the pin")
    args = parser.parse_args()
    head = subprocess.run(  # noqa: S603 - fixed argv, path from the operator
        ["git", "-C", str(args.src), "rev-parse", "HEAD"],  # noqa: S607
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    pin = declared_pin()
    table = json.loads(TABLE.read_text())
    if head != pin or table["gcsim_commit"] != pin:
        msg = f"source is at {head}, the table names {table['gcsim_commit']}, the pin is {pin}"
        raise SystemExit(msg)
    texts: dict[str, list[str]] = {}
    out: dict[str, str] = {}
    for path, line in sorted(_cited(table)):
        if path not in texts:
            texts[path] = (args.src / path).read_text().splitlines()
        out[f"{path}:{line}"] = texts[path][line - 1].strip()
    OUT.write_text(json.dumps({
        "gcsim_commit": pin,
        "note": "Each cited gcsim line, verbatim (stripped). Generated by "
                "scripts/gcsim/snapshot_particle_lines.py; do not edit by hand.",
        "constants": {k: list(v) for k, v in CONSTANT_LINES.items()},
        "lines": out,
    }, indent=1) + "\n")
    print(f"wrote {len(out)} lines to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
