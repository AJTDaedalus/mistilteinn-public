"""Derive gcsim's config-key vocabulary from the pinned source, as a committed snapshot.

    cd backend && python -m scripts.gcsim.build_key_snapshot --src /path/to/gcsim

gcsim's keys are not its directory names — the package for Blizzard Strayer is `blizzard`
while the config key is `blizzardstrayer`. The authority is `pkg/core/keys/*.dm.go`, which
is generated by gcsim's own pipeline and carries each key in a trailing comment:

    BlizzardStrayer                               // blizzardstrayer

**Committed, never fetched at runtime.** The same rule `app/data/yuanshen/` follows: this
reads a local clone at the pin and writes a JSON artifact that ships with the repo, so
nothing in `app/` needs gcsim's source or the network.

The pin is read from `docs/CROSSVAL_gcsim.md` and recorded in the output, so a snapshot built
from the wrong commit is visible rather than silent.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CROSSVAL_DOC = REPO / "docs" / "CROSSVAL_gcsim.md"
OUT = REPO / "backend" / "app" / "data" / "gcsim" / "keys.json"

#: `\tBlizzardStrayer   // blizzardstrayer` — the Go identifier, then its config key.
_ENTRY = re.compile(r"^\t(\w+)\s+//\s*(\S+)\s*$", re.M)

_FILES = {
    "characters": "character.dm.go",
    "weapons": "weapon.dm.go",
    "artifact_sets": "artifact.dm.go",
}


def declared_pin() -> str:
    """The one pin, from the one document that owns it."""
    row = re.search(r"^\| \*\*Commit\*\* \| `([0-9a-f]{40})`", CROSSVAL_DOC.read_text(), re.M)
    if row is None:
        msg = f"{CROSSVAL_DOC} no longer declares a `**Commit**` row"
        raise SystemExit(msg)
    return row.group(1)


def _keys(source: Path, filename: str) -> list[str]:
    text = (source / "pkg" / "core" / "keys" / filename).read_text()
    # The enum block lists each key once; the trailing `_Names` slice repeats the Go
    # identifiers without comments, so matching on the comment picks up each key exactly once.
    found = [key for _identifier, key in _ENTRY.findall(text)]
    if not found:
        msg = f"no keys parsed from {filename}; gcsim's generated format may have changed"
        raise SystemExit(msg)
    return sorted(set(found))


#: gcsim's action names live in a plain Go string slice, `astr`, whose order matches the
#: `Action` enum above it. Parsed rather than restated, for the reason every other snapshot in
#: this repo is derived: a re-pin that adds or renames an action becomes a reviewable diff
#: instead of a silent divergence between what we emit and what gcsim accepts.
_ASTR = re.compile(r"var astr = \[\]string\{(.*?)\}", re.S)
_ASTR_ENTRY = re.compile(r'"([a-z_]+)"')


def _actions(source: Path) -> list[str]:
    """Every name in gcsim's action **enum**, in enum order.

    Not the same as what a config may name — see `_parser_actions`, which captures the
    tokenizer's table. Both are recorded so the difference is a reviewable diff.
    """
    text = (source / "pkg" / "core" / "action" / "action.go").read_text()
    block = _ASTR.search(text)
    if block is None:
        msg = "could not find `var astr` in pkg/core/action/action.go; the format changed"
        raise SystemExit(msg)
    found = _ASTR_ENTRY.findall(block.group(1))
    # `invalid` is the zero value, not something a config can name.
    actions = [a for a in found if a != "invalid"]
    if not actions:
        msg = "no actions parsed from action.go"
        raise SystemExit(msg)
    return actions


#: `"high_plunge": action.ActionHighPlunge,` — the tokenizer's own table, in
#: `pkg/gcs/ast/keys.go`. **This, not `astr`, is what a config may name.**
#:
#: The two are not the same list and reading `astr` as though they were is the bug this
#: capture exists to prevent: gcsim's `Action` enum also carries entries that exist only to
#: hold state — `wait` and `delay` are sequencer constructs, and `special_skill` (added in
#: `1de5a4243`) is a **cooldown bucket** whose moves are authored as `skill` or `charge`.
#: Offering one of those produces a config gcsim's own parser rejects with
#: `unexpected token`.
_ACTION_KEYS = re.compile(r"var actionKeys = map\[string\]action\.Action\{(.*?)^\}", re.M | re.S)
_ACTION_KEY_ENTRY = re.compile(r'"([a-z_]+)"\s*:')


def _parser_actions(source: Path) -> list[str]:
    """Every action name gcsim's **tokenizer** accepts, sorted."""
    text = (source / "pkg" / "gcs" / "ast" / "keys.go").read_text()
    block = _ACTION_KEYS.search(text)
    if block is None:
        msg = "could not find `var actionKeys` in pkg/gcs/ast/keys.go; the format changed"
        raise SystemExit(msg)
    found = sorted(set(_ACTION_KEY_ENTRY.findall(block.group(1))))
    if not found:
        msg = "no action keys parsed from pkg/gcs/ast/keys.go"
        raise SystemExit(msg)
    return found


#: The `Action` enum block, so a Go identifier can be mapped onto the config name `astr`
#: gives at the same position. Derived by zipping the two rather than by transforming
#: `ActionHighPlunge` into `high_plunge` with string surgery — the two lists are generated
#: together and stay parallel, and a rule about underscores is a guess that would break
#: silently the first time gcsim added an action whose name did not follow it.
_ENUM_BLOCK = re.compile(r"^const \(\n(.*?)^\)", re.M | re.S)
_ENUM_ENTRY = re.compile(r"^\t(\w+)(?:\s+Action = iota)?\s*(?://.*)?$", re.M)


def _action_identifiers(source: Path) -> dict[str, str]:
    """`{Go identifier: config action name}`, positionally, from `action.go`."""
    text = (source / "pkg" / "core" / "action" / "action.go").read_text()
    block = _ENUM_BLOCK.search(text)
    astr = _ASTR.search(text)
    if block is None or astr is None:
        msg = "could not find the Action enum block or `astr` in action.go; the format changed"
        raise SystemExit(msg)
    names = _ASTR_ENTRY.findall(astr.group(1))
    identifiers = _ENUM_ENTRY.findall(block.group(1))
    # `EndActionType` terminates the parallel run; everything after it is frames-only and has
    # no config name. Truncating at it rather than at `len(names)` means a mismatch in length
    # is caught below instead of being silently zipped away.
    if "EndActionType" in identifiers:
        identifiers = identifiers[: identifiers.index("EndActionType")]
    if len(identifiers) != len(names):
        msg = (
            f"action.go's enum has {len(identifiers)} entries before EndActionType and `astr` "
            f"has {len(names)}; they are no longer parallel and this mapping cannot be trusted"
        )
        raise SystemExit(msg)
    return dict(zip(identifiers, names, strict=True))


#: `core.RegisterCharFunc(keys.KaedeharaKazuha, NewChar)` — which character a generated file is
#: for. The package directory is not the key (`kazuha` against `kaedeharakazuha`), so the file
#: has to say.
_CHAR_REGISTER = re.compile(r"core\.RegisterCharFunc\(keys\.(\w+),")

#: `paramsFor := map[action.Action][]string{ … }` — gcsim's own per-character table of which
#: parameters are valid on which action, generated by its pipeline and marked *"DO NOT EDIT"*.
#:
#: **This is the authority, and it is the reason the rotation builder can offer a hold-E to
#: exactly the characters that have one.** The alternative was grepping for `p["hold"]` in each
#: character's hand-written Go, which finds the same thing by reading the implementation rather
#: than the contract — and would quietly disagree with gcsim the first time a parameter was
#: read without being declared, or declared without being read.
_PARAMS_BLOCK = re.compile(
    r"paramsFor := map\[action\.Action\]\[\]string\{(.*?)\n\t\}", re.S,
)
_PARAMS_ENTRY = re.compile(r"action\.Action(\w+):\s*\{([^}]*)\}")
_PARAMS_NAME = re.compile(r'"([a-z_0-9]+)"')


def _character_action_params(
    source: Path, canonical: list[str],
) -> dict[str, dict[str, list[str]]]:
    """`{character key: {action: [param, …]}}`, verbatim from the generated tables.

    **Faithful, not filtered.** Which of these become actions a user can author is a policy
    decision and lives in `app/services/gcsim_keys.py`, where a test asserts every parameter
    here is classified. Filtering at capture would make a re-pin that introduced a new variant
    invisible — the snapshot would simply not mention it.
    """
    actions = _action_identifiers(source)
    by_normalised = {key.replace("_", ""): key for key in canonical}
    found: dict[str, dict[str, list[str]]] = {}
    generated = sorted((source / "internal" / "characters").rglob("zz_*.dm.go"))
    if not generated:
        msg = "no zz_*.dm.go files under internal/characters; gcsim's layout changed"
        raise SystemExit(msg)
    for path in generated:
        text = path.read_text()
        registered = _CHAR_REGISTER.search(text)
        if registered is None:
            msg = f"{path.name} registers no character; the generated format changed"
            raise SystemExit(msg)
        key = by_normalised.get(registered.group(1).lower())
        # A character gcsim implements but whose key the key file does not list would be a
        # genuine mismatch between two generated files. Refusing beats guessing, for the reason
        # `_aliases` gives.
        if key is None:
            continue
        block = _PARAMS_BLOCK.search(text)
        per_action: dict[str, list[str]] = {}
        if block is not None:
            for identifier, params in _PARAMS_ENTRY.findall(block.group(1)):
                # `_PARAMS_ENTRY` captures the enum member without its `Action` prefix, because
                # that is how the generated table spells it: `action.ActionLowPlunge`.
                name = actions.get(f"Action{identifier}")
                if name is None:
                    msg = (
                        f"{path.name} names action.Action{identifier}, which action.go's enum "
                        f"does not carry before EndActionType"
                    )
                    raise SystemExit(msg)
                per_action[name] = sorted(_PARAMS_NAME.findall(params))
        found[key] = dict(sorted(per_action.items()))
    return dict(sorted(found.items()))


def _character_implemented_actions(
    source: Path, canonical: list[str],
) -> dict[str, list[str]]:
    """`{character key: [action, …]}` — the actions each character's package implements."""
    by_normalised = {key.replace("_", ""): key for key in canonical}
    found: dict[str, list[str]] = {}
    for path in sorted((source / "internal" / "characters").rglob("zz_*.dm.go")):
        registered = _CHAR_REGISTER.search(path.read_text())
        if registered is None:
            continue
        key = by_normalised.get(registered.group(1).lower())
        if key is None:
            continue
        found[key] = _implemented_for(key, path.parent, source)
    return dict(sorted(found.items()))


#: The action methods `internal/template/character/character.go` defines as *"not
#: implemented"*, and the action each one answers. A character package that does not override
#: one inherits the error, so gcsim refuses that action **at simulation time** with
#: `<key>: action <name> not implemented`.
#:
#: **This is what tells a builder not to offer an aimed shot to a polearm user.** It is a
#: different question from `paramsFor`, which says which *parameters* an action takes, and it
#: cannot be inferred from the weapon class: Ganyu is a bow user with no `charge` (her charged
#: attack **is** the aimed shot), and gcsim implements plunges for some characters and not
#: others regardless of what they hold.
_ACTION_METHODS = {
    "Attack": "attack",
    "Aimed": "aim",
    "ChargeAttack": "charge",
    "HighPlungeAttack": "high_plunge",
    "LowPlungeAttack": "low_plunge",
    "Skill": "skill",
    "Burst": "burst",
}

#: `func (c *char) Aimed(` — the override. The receiver name varies across packages, so it is
#: matched loosely; the method name is what identifies it.
_METHOD = re.compile(r"^func \(\w+ \*\w+\) (\w+)\(", re.M)

#: Actions every character can always take: gcsim handles them outside the character, so no
#: package overrides anything for them and no character can fail to implement one.
_ALWAYS = ("dash", "jump", "walk", "swap")


#: `*cryo.Traveler` inside `type char struct { … }`, and the import that gives `cryo` its
#: path. Every Traveler variant is a thin wrapper embedding a shared implementation —
#: `internal/characters/traveler/cryo/aether` embeds `traveler/common/cryo` — so a scan that
#: stopped at the package holding `zz_aethercryo.dm.go` would conclude the Cryo Traveler
#: implements no attack, no skill and no burst. Which is what the first version of this
#: concluded, and why the derivation is checked against gcsim itself rather than trusted.
_CHAR_STRUCT = re.compile(r"^type \w+ struct \{\n(.*?)^\}", re.M | re.S)
_EMBEDDED = re.compile(r"^\t\*?(\w+)\.(\w+)\s*$", re.M)
_IMPORT = re.compile(r'"github\.com/genshinsim/gcsim/(internal/[\w/]+)"')


#: Actions a character's package **defines a method for and refuses anyway**, at run time.
#:
#: Both Aether Travelers whose element implements plunges get one: the shared method opens
#: with `if c.gender == 0 { return … "not implemented" }` — `traveler/common/cryo/plunge.go:67`
#: and `:124`, `traveler/common/pyro/plunge.go:67` and `:126`. Lumine runs the same method and
#: plunges fine.
#:
#: **No parse can see this**, which is the point: a derivation from method presence gets 865
#: of 868 character/action pairs right and is confidently wrong on these. They were found by
#: running gcsim once per pair (`scripts/gcsim/probe_implemented_actions.py`), and that probe
#: is part of the re-pin recipe rather than a one-off.
#:
#: **One of the four is invisible to the obvious probe too.** Pyro's *high* plunge refuses
#: with the message `action low_plunge not implemented` — an upstream copy-paste
#: (`common/pyro/plunge.go:128`) — so a probe matching on the action it asked about records
#: `aetherpyro high_plunge` as working. It is listed here because it was read, not matched.
_RUNTIME_REFUSALS: dict[str, tuple[str, ...]] = {
    "aethercryo": ("high_plunge", "low_plunge"),
    "aetherpyro": ("high_plunge", "low_plunge"),
}


def _implemented_actions(package: Path, source: Path) -> list[str]:
    """Which actions this character implements, following embedded implementations.

    Reads the package's methods, and the methods of any package it embeds a type from. The
    authority is `internal/template/character/character.go`: an action whose method is not
    overridden anywhere in that chain returns *"action … not implemented"* at run time.
    """
    defined: set[str] = set()
    seen: set[Path] = set()
    queue = [package]
    while queue:
        current = queue.pop()
        if current in seen or not current.is_dir():
            continue
        seen.add(current)
        for go in current.glob("*.go"):
            text = go.read_text()
            if go.name.startswith("zz_"):
                continue
            defined.update(_METHOD.findall(text))
            # Follow one embedded type per struct, to the package its selector imports.
            struct = _CHAR_STRUCT.search(text)
            if struct is None:
                continue
            imports = {path.rsplit("/", 1)[-1]: path for path in _IMPORT.findall(text)}
            for selector, _type in _EMBEDDED.findall(struct.group(1)):
                target = imports.get(selector)
                if target is not None:
                    queue.append(source / target)
    return sorted(
        {action for method, action in _ACTION_METHODS.items() if method in defined}
        | set(_ALWAYS),
    )


def _implemented_for(key: str, package: Path, source: Path) -> list[str]:
    """`_implemented_actions`, minus the actions gcsim refuses at run time for this key."""
    refused = set(_RUNTIME_REFUSALS.get(key, ()))
    return [a for a in _implemented_actions(package, source) if a not in refused]


#: `"arle":  keys.Arlecchino,` — an accepted spelling, then the canonical Go identifier.
#: `pkg/shortcut/*.dm.go` is generated by gcsim's own pipeline, like the key files.
_ALIAS = re.compile(r'^\t"([a-z0-9]+)":\s*\w+\.(\w+),\s*$', re.M)

_ALIAS_FILES = {
    "character_aliases": ("character.dm.go", "characters"),
    "weapon_aliases": ("weapon.dm.go", "weapons"),
    "artifact_set_aliases": ("artifact.dm.go", "artifact_sets"),
}


def _aliases(source: Path, filename: str, canonical: list[str]) -> dict[str, str]:
    """`{accepted spelling: canonical key}`, for spellings that are not already the key.

    **This is why a real community config was refused.** gcsim accepts `arle` for Arlecchino
    and `esco` for Escoffier, and the key snapshot carried only `arlecchino` and `escoffier` —
    so an import said *"no character on this team is gcsim's `arle`"* about a character who was
    on the team. `references/gcsim_db/arlecchino-citlali-escoffier-bennett.txt` is the config
    that showed it.

    Entries whose spelling **is** the canonical key are dropped: they are the identity, and
    keeping them would double the table for nothing. What is left is exactly the aliases.

    The Go identifier is mapped back onto the canonical key by normalising both — the shortcut
    file names `keys.Arlecchino` and the key file gives `arlecchino`, so the join is a
    lowercase comparison rather than a second parse of the enum.
    """
    text = (source / "pkg" / "shortcut" / filename).read_text()
    by_normalised = {key.replace("_", ""): key for key in canonical}
    found: dict[str, str] = {}
    for spelling, identifier in _ALIAS.findall(text):
        key = by_normalised.get(identifier.lower())
        # An alias pointing at something the key file does not list is a genuine mismatch
        # between two generated files, and guessing would put a key in the snapshot that gcsim
        # would then reject.
        if key is None or spelling == key:
            continue
        found[spelling] = key
    if not found:
        msg = f"no aliases parsed from shortcut/{filename}; the generated format may have changed"
        raise SystemExit(msg)
    return dict(sorted(found.items()))


def main() -> None:
    """Write the key snapshot from a gcsim clone."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, required=True, help="a gcsim clone")
    args = parser.parse_args()

    pin = declared_pin()
    head = subprocess.run(  # noqa: S603 - fixed argv, path from the operator
        ["git", "-C", str(args.src), "rev-parse", "HEAD"],  # noqa: S607
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    if head != pin:
        msg = (
            f"the clone is at {head} but docs/CROSSVAL_gcsim.md pins {pin}. "
            f"Check out the pin, or re-pin deliberately and re-check the citations it "
            f"invalidates — see that document."
        )
        raise SystemExit(msg)

    snapshot = {
        "pinned_commit_sha": pin,
        "source": (
            "github.com/genshinsim/gcsim — pkg/core/keys/*.dm.go, pkg/shortcut/*.dm.go, "
            "pkg/core/action/action.go and pkg/gcs/ast/keys.go"
        ),
        "note": (
            "gcsim's config keys. NOT its package directory names: the package for Blizzard "
            "Strayer is `blizzard` and the config key is `blizzardstrayer`. Generated by "
            "scripts/gcsim/build_key_snapshot.py; do not edit by hand."
        ),
        **{name: _keys(args.src, filename) for name, filename in _FILES.items()},
        "actions": _actions(args.src),
        "parser_actions": _parser_actions(args.src),
    }
    # Aliases need the canonical lists, so they are added after the comprehension above rather
    # than inside it.
    for name, (filename, canonical_name) in _ALIAS_FILES.items():
        snapshot[name] = _aliases(args.src, filename, snapshot[canonical_name])
    snapshot["character_action_params"] = _character_action_params(
        args.src, snapshot["characters"],
    )
    snapshot["character_implemented_actions"] = _character_implemented_actions(
        args.src, snapshot["characters"],
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(snapshot, indent=2, sort_keys=False) + "\n")

    counts = ", ".join(
        f"{k}={len(snapshot[k])}"
        for k in (
            *_FILES, "actions", "parser_actions", *_ALIAS_FILES, "character_action_params",
            "character_implemented_actions",
        )
    )
    print(f"wrote {OUT.relative_to(REPO)} at {pin}: {counts}")


if __name__ == "__main__":
    main()
